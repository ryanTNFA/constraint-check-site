// The hand-off memo, built from what is on screen. Order: bottom line,
// one evidence box per rated area, caveats, then appendices for analysts. Markdown is the source;
// components/markdown.mjs turns it into HTML for "Copy for email or Word" and "Print or save as PDF".
import { nodeCode, fmt, fmtSigned, fmtValue, tierLabelOf, unitHint, shortName, sourceLabel, isStale, englishList, gNorm, reasonClause } from './common.mjs';
import { plainTierOf, plainShort, bottomLine, plainSummary, topFacts, whatWouldMove, fieldQuestions, fcsNote, refSpan, tierBySetLine } from './card.mjs';
import { forkSentence } from './country_text.mjs';
export { reasonClause };

function row(cells) { return `| ${cells.map((c) => String(c ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ')).join(' | ')} |`; }
function table(head, rows) { return [row(head), row(head.map(() => '---')), ...rows.map(row)].join('\n'); }
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

export function buildMemo(ctx) {
  const { scorecard, view, registry, overrides, activeSet, peers, fcs } = ctx;
  const setting = ctx.setting || 'standard';
  const sc = scorecard; const c = sc.country; const m = sc.meta;
  const short = (id) => (registry.nodeById[id] ? registry.nodeById[id].short : id);
  const nodeOf = (id) => view.nodes.find((n) => n.id === id);
  const members = Array.isArray(peers) ? peers : (sc.comparators[activeSet] ? sc.comparators[activeSet].members : []);
  const nameOf = (iso) => { const x = (ctx.countries || []).find((k) => k.iso3 === iso); return x ? x.name : iso; };
  const snapshotYear = m.snapshot_year || Number(String(m.snapshot_id).slice(0, 4));
  const staleLimit = registry.params.recency.staleness_limit_years;
  const mock = m.mock || /mock/.test(String(m.engine_version || ''));
  const g = sc.growth_problem || {};
  const indicators = view.indicators || sc.indicators;
  const pctx = ctx.plain || { indicators, byId: Object.fromEntries(indicators.map((r) => [r.id, r])), setKey: view.setKey || activeSet, fallbackSet: activeSet, country: c.name, registry, nodes: view.nodes, view, snapshotYear };
  const bl = bottomLine({ ...pctx, view });
  const out = [];

  out.push(`# The Growth Test memo: ${c.name}`);
  out.push('');
  if (setting !== 'standard') { out.push(`> **${setting === 'exploratory' ? 'Exploratory' : 'Cautious'} reading, not the one to cite.** The ratings below use the ${setting} reading of the evidence. Standard is the only reading to cite; the figures are the same under every reading.`); out.push(''); }
  out.push(`Reading: ${setting === 'standard' ? 'Standard (the reading to cite)' : `${setting[0].toUpperCase()}${setting.slice(1)}, not the one to cite`}. Public data as of ${m.snapshot_id}. Compared with ${members.length} countries (${activeSet} set${Array.isArray(peers) ? ', edited by the user' : ''}): ${englishList(members.map(nameOf)) || 'none'}.`);
  out.push('');
  out.push(`> Prototype. Its ratings are uncalibrated and may be wrong; most areas read “unclear” because public data cannot settle them. Use this to decide what to ask, not what to fund. This tool never recommends funding.${mock ? ' THE NUMBERS IN THIS MEMO ARE MOCK DATA generated by desk/dev/mock.mjs, not engine output.' : ''}`);
  const fcsLine = fcsNote(fcs, c.iso3, c.name);
  if (fcsLine) { out.push('>'); out.push(`> ${fcsLine}`); }
  out.push('');

  // 1. bottom line
  out.push('## 1. Bottom line');
  out.push('');
  const qm = String(g.statement || '').match(/The relevant question is therefore:\s*([^.?]*)[.?]/);
  if (qm) { out.push(`**The question for ${c.name}:** ${qm[1].trim()}?`); out.push(''); }
  // the first decision, apart from the lists: a direction at the root's fork, never a rating (both sides are constraints)
  if (bl.fork) { out.push(`**First decision.** ${forkSentence(bl, c.name, (sc.top_split || {}).row)}`); out.push(''); }
  const counter = (x) => `${x.away ? `${cap(x.away.text)}.` : 'Most measures point away from a problem.'}${x.counter ? ` But ${x.counter.text}.` : ' No scored measure points the other way.'}${x.years ? ` Evidence ${x.years}.` : ''}`;
  if (bl.ruled.length) {
    out.push(`- **Ruled out.** You can stop arguing about ${englishList(bl.ruled.map((x) => x.short))}.`);
    for (const x of bl.ruled) out.push(`  - ${cap(x.short)}: ${counter(x)}`);
  }
  if (bl.probNot.length) {
    out.push(`- **Probably not the main constraint (moderate confidence):** ${englishList(bl.probNot.map((x) => x.short))}. This is about what holds back private investment, not household needs; do not drop a program on ‘probably not’ alone.`);
    for (const x of bl.probNot) out.push(`  - ${cap(x.short)}: ${counter(x)}`);
  }
  if (!bl.ruled.length && !bl.probNot.length) out.push(`- **Nothing can be ruled out for ${c.name} yet.** For ${bl.nUnclear} of ${bl.nAreas} areas the public data are too thin, point both ways, or need a sector study.`);
  if (bl.look.length) {
    out.push(`- **Worth a closer look (not established):** ${englishList(bl.look.map((x) => (x.ev !== x.node ? `${x.evShort}, part of ‘${x.short}’` : x.short)))}.`);
    for (const x of bl.look) out.push(`  - ${cap(x.ev !== x.node ? x.evShort : x.short)}: ${x.facts.length ? `${cap(x.facts.map((f) => f.text).join('; and '))}.` : 'see the evidence box below.'} ${x.node.tier === 'likely_binding' ? 'Still to be confirmed in-country.' : 'Not established: confirm in-country before relying on it.'}`);
  } else out.push(`- **No area stands out yet:** none reaches ‘worth a closer look’.`);
  if (bl.nUnclear) {
    const gr = bl.groups;
    out.push(`- **Unclear (${bl.nUnclear} area${bl.nUnclear === 1 ? '' : 's'}), for different reasons:**`);
    if (gr.oneKind.length) out.push(`  - Only one kind of evidence speaks (${gr.oneKind.length}): ${englishList(gr.oneKind.map((x) => x.short))}. A second kind would settle it either way.${bl.closest ? ` Closest to a call: ${bl.closest.short} (leans ${bl.closest.node.N > 0 ? 'toward' : 'away from'} a problem).` : ''}`);
    if (gr.mixed.length) out.push(`  - The evidence points both ways (${gr.mixed.length}): ${englishList(gr.mixed.map((x) => x.short))}. Possibly a problem for some sectors or regions only.`);
    if (gr.toolGap.length) out.push(`  - The tool has no adequate measure yet (${gr.toolGap.length}): ${englishList(gr.toolGap.map((x) => x.short))}. A gap in the tool, not in ${c.name}'s data; ask an economist.`);
    if (gr.dataGap.length) out.push(`  - Too little recent data for ${c.name} (${gr.dataGap.length}): ${englishList(gr.dataGap.map((x) => x.short))}. New data would settle it.`);
    if (gr.sector.length) out.push(`  - Needs a sector study (${gr.sector.length}): ${englishList(gr.sector.map((x) => x.short))}.`);
    for (const x of gr.elimination) out.push(`  - Judged by elimination: ${x.short}. It can be called only once the other causes of low returns are ruled out${x.node.elimination && x.node.elimination.direction !== 'none' ? `; today the evidence leans ${x.node.elimination.direction === 'toward' ? 'toward' : 'away from'} a problem` : ''}.`);
  }
  if (bl.towardLeans.length || bl.awayLeans.length) {
    const parts = [];
    if (bl.towardLeans.length) parts.push(`toward a problem: ${englishList(bl.towardLeans.slice(0, 3).map((x) => x.short))}${bl.towardLeans[0].fact ? ` (${bl.towardLeans[0].short}: ${bl.towardLeans[0].fact.text.replace(/[()]/g, '')})` : ''}`);
    if (bl.awayLeans.length) parts.push(`away: ${englishList(bl.awayLeans.slice(0, 3).map((x) => x.short))}`);
    out.push(`- **Leans, below the bar (not a verdict):** ${parts.join('; ')}.`);
  }
  if (bl.firmsTop) {
    const r = bl.firmsTop.r; const mm = String(r.name || '').match(/choosing (.+?) as their biggest obstacle/i);
    out.push(`- Firms rank ${mm ? mm[1] : shortName(r).toLowerCase()} as their biggest obstacle (${fmt(r.value_ref, 0)}% name it first, Enterprise Surveys ${refSpan(r)}), but complaints alone cannot establish a constraint${bl.firmsTop.toolGap ? ', and the tool has no measure of its cost yet' : ''}.`);
  }
  out.push('');

  // 3. one evidence box per rated area
  const rated = view.nodes.filter((n) => !/^N11\./.test(n.id) && ['likely_binding', 'candidate', 'probably_not', 'ruled_out'].includes(n.tier));
  out.push('## 2. Evidence for the rated areas');
  out.push('');
  if (!rated.length) { out.push('No area has a rating other than unclear. Open any area on the page for what would settle it.'); out.push(''); }
  for (const n of rated) {
    const ev = n.sub_nodes && n.rollup_from ? nodeOf(n.rollup_from) || n : n;
    const title = ev !== n ? `${cap(plainShort(registry, ev.id))} (part of ${plainShort(registry, n.id)})` : cap(plainShort(registry, n.id));
    out.push(`### ${title}: ${plainTierOf(n.id, n.tier).toLowerCase()}${overrides[n.id] ? ` (your override: ${plainTierOf(n.id, overrides[n.id].tier).toLowerCase()})` : ''}`);
    out.push('');
    out.push(plainSummary(n, pctx));
    out.push('');
    const facts = [...topFacts(ev, pctx, n.N != null && n.N < 0 ? -1 : 1, 2), ...topFacts(ev, pctx, n.N != null && n.N < 0 ? 1 : -1, 1)];
    if (facts.length) {
      out.push(table(['Indicator', 'Value', 'Years', 'Source', 'Points'], facts.map((f) => [shortName(f.r), `${fmtValue(f.r, f.r.value_ref)} ${unitHint(f.r)}`.trim(), refSpan(f.r), sourceLabel(f.r), f.family.signal > 0 ? 'toward a problem' : 'away from a problem'])));
      out.push('');
    }
    const setLine = tierBySetLine(n, activeSet, Array.isArray(peers));
    if (setLine) { out.push(setLine); out.push(''); }
    const moves = whatWouldMove(n, pctx);
    if (moves.length) { out.push(`What would move it: ${moves.join(' ')}`); out.push(''); }
    const qs = fieldQuestions(n, view.nodes);
    if (qs.length) { out.push(`If you have two days in-country: ${qs.join(' ')}`); out.push(''); }
  }

  // 4. caveats
  out.push('## 3. Caveats');
  out.push('');
  out.push('- Prototype: the ratings are uncalibrated, and most areas read “unclear” because public data cannot settle them.');
  out.push('- Public data only, no field work. Every rating is about what holds back private investment, not household needs.');
  if (fcsLine) out.push(`- ${fcsLine}`);
  const sensitive = view.nodes.filter((n) => !/^N11\./.test(n.id) && n.tier_by_set && new Set(Object.entries(n.tier_by_set).filter(([k]) => k !== 'custom').map(([, t]) => t)).size > 1);
  if (sensitive.length) out.push(`- Ratings that depend on the comparison countries: ${sensitive.map((n) => `${plainShort(registry, n.id)} (${Object.entries(n.tier_by_set).filter(([k]) => k !== 'custom').map(([k, t]) => `${k}: ${plainTierOf(n.id, t).toLowerCase()}`).join('; ')})`).join('; ')}.`);
  const ovs = Object.entries(overrides || {});
  if (ovs.length) {
    out.push('- Overrides below are the user\'s judgment, shown next to the tool\'s rating.');
    out.push('');
    out.push(table(['Area', 'Tool rating', 'Your rating', 'Note'], ovs.map(([id, v]) => { const n = nodeOf(id); return [`${nodeCode(id)} ${short(id)}`, plainTierOf(id, n && n.tier), plainTierOf(id, v.tier), v.note || '']; })));
  }
  out.push('');

  // appendices for analysts
  out.push('## Appendix A. The growth problem');
  out.push('');
  const cleaned = String(g.statement || '').replace(/\s*Provisional top-split reading:[^()]*(\([^)]*\))?\.?/g, '').trim();
  out.push(cleaned || '—');
  out.push('');
  const gn = gNorm(g); const { g1, g2, g3, g4, g5, g6, g7 } = gn;
  out.push(table(['Statistic', 'Value', 'Comparison'], [
    ['G1 growth, 10-year average (% a year)', fmt(g1.avg10, 2), `20-year ${fmt(g1.avg20, 2)}; structural peers median ${fmt(g1.peers10, 2)}; region median ${fmt(g1.region10, 2)}; rank ${g1.rank ?? '—'} of ${g1.n ?? '—'}`],
    ['G2 convergence residual (t)', fmtSigned(g2.t, 2), g2.method],
    ['G3 peak year of GDP per capita', g3.peakYear ?? '—', `${g3.yearsSince ?? '—'} years since peak; ${fmt(g3.shortfall, 1)}% below peak`],
    ['G4 growth break', g4.reported ? g4.breakYear : 'none ≥ threshold', `${fmtSigned(g4.change, 2)} pp (${fmt(g4.before, 2)} → ${fmt(g4.after, 2)}); ${g4.method}`],
    ['G5 volatility (s.d. of growth, 20y)', fmt(g5.sd, 2), `peers median ${fmt(g5.peers, 2)}; universe percentile ${g5.pct == null ? '—' : Math.round(g5.pct)}`],
    ['G6 investment residual (t)', fmtSigned(g6.t, 2), `GFCF ${fmt(g6.value, 1)}% of GDP (${g6.year ?? '—'}); ${g6.split}`],
    ['G7 savings residual (t)', fmtSigned(g7.savings.t, 2), `savings ${fmt(g7.savings.value, 1)}% of GDP; current account ${fmt(g7.cab.value, 1)}%; FDI ${fmt(g7.fdi.value, 2)}%`],
  ]));
  out.push('');
  const ts = sc.top_split || {};
  const n0 = nodeOf('N0');
  out.push(`First-decision pattern (a pattern, not a verdict): the “${ts.label || (ts.row || '—').replace(/_/g, ' ')}” row of the finance-or-returns table. The four finance tests read the fork as ‘${n0 ? plainTierOf('N0', n0.tier).toLowerCase() : '—'}’${n0 && n0.N != null ? ` (N = ${fmtSigned(n0.N)}, the finance side’s score)` : ''}: a direction, not a rating, since both sides of the fork are constraints.`);
  out.push('');

  out.push('## Appendix B. Rule detail for analysts');
  out.push('');
  const listed = view.nodes.filter((n) => n.tier !== 'context_only' && n.tier_reason);
  for (const n of listed) out.push(`- ${nodeCode(n.id)} ${short(n.id)} (${tierLabelOf(n.id, n.tier)}): ${n.tier_reason}`);
  out.push('');

  out.push('## Appendix C. Provenance summary');
  out.push('');
  const used = indicators.filter((r) => r.value_ref != null);
  const bySource = {};
  for (const r of used) { const k = sourceLabel(r); bySource[k] = (bySource[k] || 0) + 1; }
  const yearsUsed = used.map((r) => r.year_ref).filter((y) => Number.isFinite(y));
  const staleN = used.filter((r) => isStale(r.year_ref, snapshotYear, staleLimit)).length;
  out.push(`${used.length} of ${indicators.length} registry indicators have a value for ${c.name} in the reference window (${yearsUsed.length ? `${Math.min(...yearsUsed)}–${Math.max(...yearsUsed)}` : '—'}); ${staleN} are older than ${staleLimit} years. Values are the mean of the latest three years where they exist. Sources: ${Object.entries(bySource).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} (${v})`).join(', ')}. The full table, with every value, year, source and flag, is under Areas › Comparison countries and every number › Provenance. Snapshot ${m.snapshot_id}, rubric ${m.rubric_version}, engine ${m.engine_version}.`);
  out.push('');
  out.push('---');
  const local = /^(localhost|127\.0\.0\.1|\[::1\])$/.test(location.hostname);
  out.push(local ? `Interactive version: country.html?iso=${c.iso3} on The Growth Test (this memo was generated from a local copy, so no public link exists).` : `Interactive version, with the same comparison countries and overrides: ${location.href}`);
  out.push('');
  out.push('This tool never recommends funding; it states what the public evidence can and cannot support.');
  return out.join('\n');
}

